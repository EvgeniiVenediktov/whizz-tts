"""Local OmniVoice backend — generates each phrase with the local model.

Accent/voice comes from an optional voice-clone reference (a short clip + its
transcript), e.g. a phrase generated by Gemini in the target accent
(scripts/make_accent_reference.py). OmniVoice clones it for every phrase. No
cloud, no per-request quota — but the model isn't thread-safe, so generation
runs sequentially.

src.model (torch/omnivoice) is imported lazily; tests inject `generate_fn`.
"""
from typing import Callable, Optional

from .base import SynthResult

SAMPLE_RATE = 24_000


class LocalOmniVoiceBackend:
    name = "local"

    def __init__(self, ref_audio: Optional[str] = None,
                 ref_text: Optional[str] = None, voice: str = "local",
                 generate_fn: Optional[Callable] = None):
        self.ref_audio = ref_audio      # clone reference clip (accent/voice)
        self.ref_text = ref_text        # its transcript
        self._voice = voice             # label for the output dir
        self._generate_fn = generate_fn  # test seam; bypasses the real model

    def synthesize(self, text: str, *, voice: Optional[str] = None,
                   language: Optional[str] = None,
                   ssml: Optional[str] = None) -> SynthResult:
        gen = self._generate_fn
        if gen is None:
            from src.model import ensure_loaded, generate
            ensure_loaded()
            gen = generate
        pcm = gen(text, self.ref_audio, self.ref_text)
        return SynthResult(pcm=pcm, sample_rate=SAMPLE_RATE, billed_chars=len(text))
